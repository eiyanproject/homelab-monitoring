#!/bin/sh
# Generate Grafana contact points, message templates, notification policies
# and the backup-window mute timing from .env.
#
# Why this exists instead of ${VAR} interpolation in a committed file:
# Grafana refuses to load a contact point whose url/token is empty, and a
# failed provisioning run crash-loops the container. So a stack with no alert
# channels yet could not start at all. Generating the file means an
# unconfigured channel is ABSENT rather than empty, and Grafana always starts.
#
# POSIX sh on purpose: this runs both on the LXC (bash) and inside the Alpine
# control container (busybox sh).
#
#   ./render-alerting.sh [project_dir]      default: /srv/monitoring
set -eu

PROJECT_DIR="${1:-/srv/monitoring}"
ENV_FILE="${PROJECT_DIR}/.env"
OUT_DIR="${PROJECT_DIR}/config/grafana/provisioning/alerting"
CP="${OUT_DIR}/contact-points.yml"
NP="${OUT_DIR}/notification-policies.yml"

[ -f "$ENV_FILE" ] || { echo "render-alerting: no $ENV_FILE" >&2; exit 1; }
mkdir -p "$OUT_DIR"

env_get() {
  grep -E "^$1=" "$ENV_FILE" 2>/dev/null | head -1 | cut -d= -f2- | sed 's/^"//; s/"$//'
}

NTFY=$(env_get NTFY_URL)
NTFY_TOKEN=$(env_get NTFY_TOKEN)
NTFY_TEMPLATE=$(env_get NTFY_TEMPLATE); NTFY_TEMPLATE=${NTFY_TEMPLATE:-yes}
DISCORD=$(env_get DISCORD_WEBHOOK_URL)
TG_TOKEN=$(env_get TELEGRAM_BOT_TOKEN)
TG_CHAT=$(env_get TELEGRAM_CHAT_ID)
MUTE_WINDOW=$(env_get ALERT_MUTE_WINDOW)
TZ_NAME=$(env_get ALERT_TIMEZONE); TZ_NAME=${TZ_NAME:-UTC}
CRIT_REPEAT=$(env_get CRITICAL_REPEAT); CRIT_REPEAT=${CRIT_REPEAT:-4h}
WARN_REPEAT=$(env_get WARNING_REPEAT); WARN_REPEAT=${WARN_REPEAT:-24h}

HAVE_NTFY=no;    [ -n "$NTFY" ] && HAVE_NTFY=yes
HAVE_DISCORD=no; [ -n "$DISCORD" ] && HAVE_DISCORD=yes
HAVE_TG=no;      [ -n "$TG_TOKEN" ] && [ -n "$TG_CHAT" ] && HAVE_TG=yes

if [ "$HAVE_NTFY" = no ] && [ "$HAVE_DISCORD" = no ] && [ "$HAVE_TG" = no ]; then
  rm -f "$CP" "$NP"
  echo "render-alerting: no channels configured - rules will still load and"
  echo "                 evaluate, they just will not notify anywhere yet."
  exit 0
fi

# ntfy publishes the raw request body as the message. Grafana's webhook body is
# its whole JSON payload, often over ntfy's 4 KB message limit, so it arrives
# as an attachment you cannot read on a lock screen. ntfy's template mode
# (?tpl=yes, ntfy >= 2.6) reads the JSON and uses only its title and message
# fields, which the hm.* templates below fill. NTFY_TEMPLATE=no turns it off
# for an older ntfy. Priority and tag are fixed per route, hence two URLs.
ntfy_url() {  # $1 = priority, $2 = tag
  case "$NTFY" in *\?*) sep='&' ;; *) sep='?' ;; esac
  u="${NTFY}${sep}p=$1&ta=$2"
  if [ "$NTFY_TEMPLATE" = yes ]; then
    u="${u}&tpl=yes&t=%7B%7B.title%7D%7D&m=%7B%7B.message%7D%7D"
  fi
  printf '%s' "$u"
}

ntfy_receiver() {  # $1 = uid, $2 = priority, $3 = tag
  echo "      - uid: $1"
  echo "        type: webhook"
  echo "        settings:"
  echo "          url: \"$(ntfy_url "$2" "$3")\""
  echo "          httpMethod: POST"
  echo "          title: '{{ template \"hm.title\" . }}'"
  echo "          message: '{{ template \"hm.message\" . }}'"
  # A self-hosted ntfy set to deny-all needs a token. Without this the topic
  # name would be the only secret, and a leaked one lets anyone read alerts.
  if [ -n "$NTFY_TOKEN" ]; then
    echo "          authorization_scheme: Bearer"
    echo "          authorization_credentials: ${NTFY_TOKEN}"
  fi
}

discord_receiver() {  # $1 = uid
  echo "      - uid: $1"
  echo "        type: discord"
  echo "        settings:"
  echo "          url: ${DISCORD}"
  echo "          title: '{{ template \"hm.title\" . }}'"
  echo "          message: '{{ template \"hm.message\" . }}'"
}

telegram_receiver() {  # $1 = uid
  echo "      - uid: $1"
  echo "        type: telegram"
  echo "        settings:"
  echo "          bottoken: ${TG_TOKEN}"
  echo "          chatid: \"${TG_CHAT}\""
  # printf, not echo: dash's echo would turn the \n into a real newline.
  printf '%s\n' "          message: '{{ template \"hm.title\" . }}{{ \"\\n\" }}{{ template \"hm.message\" . }}'"
}

# ---- templates + contact points ------------------------------------------
{
  echo "apiVersion: 1"
  echo ""
  echo "# GENERATED by scripts/render-alerting.sh from .env - do not edit by hand."
  echo "# Re-run that script (or use the control panel) after changing channels."
  echo ""
  # One message shape for every channel: what is wrong, then what to do. Every
  # rule carries a runbook annotation, and the runbook is the part you need at
  # 3am. No dollar signs: Grafana expands them in provisioning files.
  cat <<'TPL'
templates:
  - orgID: 1
    name: hm
    template: |
      {{ define "hm.title" }}{{ if eq .Status "firing" }}[{{ .CommonLabels.severity | toUpper }}{{ if gt (len .Alerts.Firing) 1 }} x{{ len .Alerts.Firing }}{{ end }}]{{ else }}[RESOLVED]{{ end }} {{ .CommonLabels.alertname }}{{ end }}
      {{ define "hm.message" }}{{ range .Alerts.Firing }}- {{ or .Annotations.summary .Labels.alertname }}
      {{ end }}{{ if .Alerts.Firing }}{{ with .CommonAnnotations.runbook }}
      What to do: {{ . }}
      {{ end }}{{ end }}{{ range .Alerts.Resolved }}- resolved: {{ or .Annotations.summary .Labels.alertname }}
      {{ end }}{{ end }}

TPL
  echo "contactPoints:"

  # critical-all: every configured channel. If it is worth waking you, it is
  # worth sending three ways - any one of them can be the broken one.
  echo "  - orgId: 1"
  echo "    name: critical-all"
  echo "    receivers:"
  if [ "$HAVE_NTFY" = yes ];    then ntfy_receiver hm-crit-ntfy urgent rotating_light; fi
  if [ "$HAVE_TG" = yes ];      then telegram_receiver hm-crit-telegram; fi
  if [ "$HAVE_DISCORD" = yes ]; then discord_receiver hm-crit-discord; fi

  # warnings: Discord if there is one (history you skim), otherwise ntfy at
  # normal priority - not critical-all, which would page you for a warning.
  echo "  - orgId: 1"
  echo "    name: warnings"
  echo "    receivers:"
  if [ "$HAVE_DISCORD" = yes ]; then
    discord_receiver hm-warn-discord
  elif [ "$HAVE_NTFY" = yes ]; then
    ntfy_receiver hm-warn-ntfy default warning
  else
    telegram_receiver hm-warn-telegram
  fi
} > "$CP"

# ---- mute timing over the backup window ----------------------------------
# The nightly vzdump spikes I/O wait and PSI on every guest; without this the
# warnings it causes train you to ignore warnings within a week. Criticals are
# never muted. ALERT_MUTE_WINDOW=HH:MM-HH:MM in ALERT_TIMEZONE; a window past
# midnight is split in two, because a time range cannot wrap.
MUTE_YAML=""
MUTE_REF=""
if [ -n "$MUTE_WINDOW" ]; then
  START=${MUTE_WINDOW%-*}; END=${MUTE_WINDOW#*-}
  case "$START$END" in
    [0-2][0-9]:[0-5][0-9][0-2][0-9]:[0-5][0-9]) ;;
    *) echo "render-alerting: ALERT_MUTE_WINDOW must be HH:MM-HH:MM, got '$MUTE_WINDOW'" >&2; exit 1 ;;
  esac
  if [ "$(echo "$START" | tr -d :)" -lt "$(echo "$END" | tr -d :)" ]; then
    TIMES="          - {start_time: \"$START\", end_time: \"$END\"}"
  else
    TIMES="          - {start_time: \"$START\", end_time: \"24:00\"}
          - {start_time: \"00:00\", end_time: \"$END\"}"
  fi
  MUTE_YAML="
muteTimes:
  - orgId: 1
    name: backup-window
    time_intervals:
      - location: \"${TZ_NAME}\"
        times:
${TIMES}
"
  MUTE_REF="        mute_time_intervals: [backup-window]"
fi

# ---- notification policies ------------------------------------------------
cat > "$NP" <<EOF
apiVersion: 1

# GENERATED by scripts/render-alerting.sh from .env - do not edit by hand.
${MUTE_YAML}
policies:
  - orgId: 1
    receiver: warnings
    # host: the PVE guest and node rules label by host, so each guest gets its
    # own notification instead of one lumped across the cluster.
    group_by: [alertname, node, host, guest]
    routes:
      # Wake me up.
      - receiver: critical-all
        object_matchers:
          - ["severity", "=", "critical"]
        group_wait: 30s
        group_interval: 5m
        repeat_interval: ${CRIT_REPEAT}

      # Look at it this week.
      - receiver: warnings
        object_matchers:
          - ["severity", "=", "warning"]
        group_wait: 5m
        group_interval: 30m
        repeat_interval: ${WARN_REPEAT}
${MUTE_REF}
EOF

CHANNELS=""
[ "$HAVE_NTFY" = yes ]    && CHANNELS="${CHANNELS} ntfy"
[ "$HAVE_TG" = yes ]      && CHANNELS="${CHANNELS} telegram"
[ "$HAVE_DISCORD" = yes ] && CHANNELS="${CHANNELS} discord"
echo "render-alerting: configured ->${CHANNELS}"
if [ "$HAVE_NTFY" = yes ] && [ -z "$NTFY_TOKEN" ]; then
  echo "render-alerting: WARNING NTFY_TOKEN is empty - a deny-all ntfy (what setup-oci.sh builds) rejects every post"
fi
if [ -n "$MUTE_WINDOW" ]; then
  echo "render-alerting: warnings muted ${MUTE_WINDOW} ${TZ_NAME}"
fi
echo "render-alerting: test delivery with  sh scripts/test-alert.sh ${PROJECT_DIR}"
